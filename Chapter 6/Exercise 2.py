# Exercise 2: Given that fruit is a string, what does fruit[:] mean?
# In Python, `fruit[:]` is a slicing operation that creates a new string that is a copy
# of the entire `fruit` string. The colon `:` indicates that you want to include all characters
# from the beginning to the end of the string. Therefore, `fruit[:]` will return a new string
# that is identical to `fruit`.
